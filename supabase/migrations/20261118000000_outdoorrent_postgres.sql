-- Trigger updated_at, pengganti ON UPDATE current_timestamp()
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- users
-- ---------------------------------------------------------------------------
create table if not exists public.users (
  id integer generated by default as identity primary key,
  email varchar(255) not null,
  password varchar(255) not null,
  name varchar(255) not null,
  phone varchar(20),
  address text,
  profile_image varchar(255),
  role text not null default 'customer' check (role in ('customer', 'admin')),
  is_active boolean not null default true,
  auth_user_id uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint users_email_unique unique (email)
);

create index if not exists idx_users_role on public.users (role);
create index if not exists idx_users_is_active on public.users (is_active);
create index if not exists idx_users_auth_user_id on public.users (auth_user_id);

drop trigger if exists users_set_updated_at on public.users;
create trigger users_set_updated_at
  before update on public.users
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- categories
-- ---------------------------------------------------------------------------
create table if not exists public.categories (
  id integer generated by default as identity primary key,
  name varchar(100) not null,
  description text,
  icon varchar(100),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_categories_name on public.categories (name);

drop trigger if exists categories_set_updated_at on public.categories;
create trigger categories_set_updated_at
  before update on public.categories
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- equipments
-- ---------------------------------------------------------------------------
create table if not exists public.equipments (
  id integer generated by default as identity primary key,
  category_id integer not null references public.categories (id) on update cascade,
  name varchar(255) not null,
  description text,
  price_per_day numeric(10, 2) not null,
  stock integer not null default 0,
  deposit numeric(10, 2) not null default 0,
  rating_avg numeric(3, 2) not null default 0,
  total_reviews integer not null default 0,
  total_bookings integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_equipments_category_id on public.equipments (category_id);
create index if not exists idx_equipments_is_active on public.equipments (is_active);
create index if not exists idx_equipments_rating_avg on public.equipments (rating_avg);
create index if not exists idx_equipments_price_per_day on public.equipments (price_per_day);

drop trigger if exists equipments_set_updated_at on public.equipments;
create trigger equipments_set_updated_at
  before update on public.equipments
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- equipment_images
-- ---------------------------------------------------------------------------
create table if not exists public.equipment_images (
  id integer generated by default as identity primary key,
  equipment_id integer not null references public.equipments (id) on delete cascade on update cascade,
  image_url varchar(255) not null,
  is_primary boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists idx_equipment_images_equipment_id on public.equipment_images (equipment_id);
create index if not exists idx_equipment_images_is_primary on public.equipment_images (is_primary);
create index if not exists idx_equipment_images_sort_order on public.equipment_images (sort_order);

-- ---------------------------------------------------------------------------
-- bookings
-- ---------------------------------------------------------------------------
create table if not exists public.bookings (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users (id) on update cascade,
  booking_code varchar(50) not null,
  pickup_date date not null,
  return_date date not null,
  actual_return_date date,
  total_days integer not null,
  subtotal numeric(12, 2) not null,
  deposit_total numeric(12, 2) not null default 0,
  late_fee numeric(12, 2) not null default 0,
  damage_fee numeric(12, 2) not null default 0,
  deposit_refund numeric(12, 2) not null default 0,
  grand_total numeric(12, 2) not null,
  status text not null default 'pending_payment'
    check (status in ('pending_payment', 'pending_verification', 'confirmed', 'in_use', 'completed', 'cancelled', 'rejected')),
  notes text,
  cancellation_reason text,
  return_condition text check (return_condition is null or return_condition in ('good', 'damaged', 'lost')),
  return_notes text,
  auto_cancel_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint bookings_booking_code_unique unique (booking_code)
);

create index if not exists idx_bookings_user_id on public.bookings (user_id);
create index if not exists idx_bookings_status on public.bookings (status);
create index if not exists idx_bookings_pickup_date on public.bookings (pickup_date);
create index if not exists idx_bookings_return_date on public.bookings (return_date);
create index if not exists idx_bookings_auto_cancel_at on public.bookings (auto_cancel_at);
create index if not exists idx_bookings_created_at on public.bookings (created_at);

drop trigger if exists bookings_set_updated_at on public.bookings;
create trigger bookings_set_updated_at
  before update on public.bookings
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- booking_items
-- ---------------------------------------------------------------------------
create table if not exists public.booking_items (
  id integer generated by default as identity primary key,
  booking_id integer not null references public.bookings (id) on delete cascade on update cascade,
  equipment_id integer not null references public.equipments (id) on update cascade,
  quantity integer not null,
  price_per_day numeric(10, 2) not null,
  subtotal numeric(12, 2) not null
);

create index if not exists idx_booking_items_booking_id on public.booking_items (booking_id);
create index if not exists idx_booking_items_equipment_id on public.booking_items (equipment_id);

-- ---------------------------------------------------------------------------
-- payments
-- ---------------------------------------------------------------------------
create table if not exists public.payments (
  id integer generated by default as identity primary key,
  booking_id integer not null references public.bookings (id) on delete cascade on update cascade,
  amount numeric(12, 2) not null,
  payment_proof varchar(255),
  bank_name varchar(100),
  account_name varchar(255),
  account_number varchar(50),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  payment_date timestamptz,
  verified_at timestamptz,
  verified_by integer references public.users (id) on delete set null on update cascade,
  rejection_reason text,
  created_at timestamptz not null default now()
);

create index if not exists idx_payments_booking_id on public.payments (booking_id);
create index if not exists idx_payments_status on public.payments (status);
create index if not exists idx_payments_verified_by on public.payments (verified_by);

-- ---------------------------------------------------------------------------
-- reviews
-- ---------------------------------------------------------------------------
create table if not exists public.reviews (
  id integer generated by default as identity primary key,
  booking_id integer not null references public.bookings (id) on delete cascade on update cascade,
  user_id integer not null references public.users (id) on delete cascade on update cascade,
  equipment_id integer not null references public.equipments (id) on delete cascade on update cascade,
  rating smallint not null check (rating >= 1 and rating <= 5),
  comment text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint reviews_unique_booking_equipment unique (booking_id, equipment_id)
);

create index if not exists idx_reviews_user_id on public.reviews (user_id);
create index if not exists idx_reviews_equipment_id on public.reviews (equipment_id);
create index if not exists idx_reviews_rating on public.reviews (rating);

drop trigger if exists reviews_set_updated_at on public.reviews;
create trigger reviews_set_updated_at
  before update on public.reviews
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- login_attempts
-- ---------------------------------------------------------------------------
create table if not exists public.login_attempts (
  id integer generated by default as identity primary key,
  ip_address varchar(45) not null,
  email varchar(255) not null,
  attempted_at timestamptz not null default now()
);

create index if not exists idx_login_attempts_ip_email_attempted on public.login_attempts (ip_address, email, attempted_at);
create index if not exists idx_login_attempts_attempted_at on public.login_attempts (attempted_at);

