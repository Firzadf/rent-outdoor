-- ---------------------------------------------------------------------------
-- Row Level Security, policy MVP. Lihat catatan 8 di header.
-- ---------------------------------------------------------------------------
alter table public.users enable row level security;
alter table public.categories enable row level security;
alter table public.equipments enable row level security;
alter table public.equipment_images enable row level security;
alter table public.bookings enable row level security;
alter table public.booking_items enable row level security;
alter table public.payments enable row level security;
alter table public.reviews enable row level security;
alter table public.login_attempts enable row level security;

-- Katalog: baca publik
drop policy if exists "categories_read_all" on public.categories;
create policy "categories_read_all" on public.categories for select using (true);

drop policy if exists "equipments_read_all" on public.equipments;
create policy "equipments_read_all" on public.equipments for select using (true);

drop policy if exists "equipment_images_read_all" on public.equipment_images;
create policy "equipment_images_read_all" on public.equipment_images for select using (true);

drop policy if exists "reviews_read_all" on public.reviews;
create policy "reviews_read_all" on public.reviews for select using (true);

-- Katalog: tulis hanya untuk login. Admin dikelola di level aplikasi.
drop policy if exists "categories_write_auth" on public.categories;
create policy "categories_write_auth" on public.categories for all using (auth.role() = 'authenticated');

drop policy if exists "equipments_write_auth" on public.equipments;
create policy "equipments_write_auth" on public.equipments for all using (auth.role() = 'authenticated');

drop policy if exists "equipment_images_write_auth" on public.equipment_images;
create policy "equipment_images_write_auth" on public.equipment_images for all using (auth.role() = 'authenticated');

-- Booking, item, pembayaran: hanya untuk login. Perketat ke pemilik
-- setelah users.auth_user_id terisi dan tertaut ke auth.uid().
drop policy if exists "bookings_all_auth" on public.bookings;
create policy "bookings_all_auth" on public.bookings for all using (auth.role() = 'authenticated');

drop policy if exists "booking_items_all_auth" on public.booking_items;
create policy "booking_items_all_auth" on public.booking_items for all using (auth.role() = 'authenticated');

drop policy if exists "payments_all_auth" on public.payments;
create policy "payments_all_auth" on public.payments for all using (auth.role() = 'authenticated');

-- Review: tulis untuk login
drop policy if exists "reviews_write_auth" on public.reviews;
create policy "reviews_write_auth" on public.reviews for insert with check (auth.role() = 'authenticated');

-- Users: baca dan ubah profil sendiri untuk login. Insert profil dilakukan
-- lewat service_role saat register Supabase Auth, atau lewat aplikasi.
drop policy if exists "users_read_auth" on public.users;
create policy "users_read_auth" on public.users for select using (auth.role() = 'authenticated');

drop policy if exists "users_update_auth" on public.users;
create policy "users_update_auth" on public.users for update using (auth.role() = 'authenticated');

-- login_attempts: tanpa policy untuk anon dan authenticated, jadi hanya
-- service_role yang bisa baca dan tulis. Ini disengaja.

-- ---------------------------------------------------------------------------
-- Storage buckets
-- ---------------------------------------------------------------------------
insert into storage.buckets (id, name, public) values
  ('equipment-images', 'equipment-images', true),
  ('payment-proofs', 'payment-proofs', false)
on conflict (id) do nothing;

-- Policy storage: foto alat bisa dibaca publik, upload hanya untuk login.
-- Bukti bayar hanya untuk login.
drop policy if exists "equipment_images_storage_read" on storage.objects;
create policy "equipment_images_storage_read" on storage.objects
  for select using (bucket_id = 'equipment-images');

drop policy if exists "equipment_images_storage_write_auth" on storage.objects;
create policy "equipment_images_storage_write_auth" on storage.objects
  for insert with check (bucket_id = 'equipment-images' and auth.role() = 'authenticated');

drop policy if exists "equipment_images_storage_update_auth" on storage.objects;
create policy "equipment_images_storage_update_auth" on storage.objects
  for update using (bucket_id = 'equipment-images' and auth.role() = 'authenticated');

drop policy if exists "equipment_images_storage_delete_auth" on storage.objects;
create policy "equipment_images_storage_delete_auth" on storage.objects
  for delete using (bucket_id = 'equipment-images' and auth.role() = 'authenticated');

drop policy if exists "payment_proofs_storage_all_auth" on storage.objects;
create policy "payment_proofs_storage_all_auth" on storage.objects
  for all using (bucket_id = 'payment-proofs' and auth.role() = 'authenticated');

commit;

